function [wingLocs] = MarkWing(im,method,wingNames,nonlinVis)
%Marks the region of an image containing each lep wing, based on user input
%   Displays an image and asks the user to mark the locations of the four
%   wings of a moth/butterfly. There are two marking methods: 'crosshair'
%   asks the user to crop to all four wings, then click in the center to
%   separate the cropped region into 4 quadrants; this is best when the
%   wings can be cleanly separated by a cross. The 'rectangles' method asks
%   the user to separately mark crop rectangles for each of the four wings;
%   this is best when the wings cannot be cleanly separated (i.e. they
%   aren't each in one of the four quadrants generated by the 'crosshair'
%   method). Crop rectangles (format [x y width height], see doc imcrop) 
%   are returned for each wing as fields in the structure wingLocs, with 
%   fields named based on wingNames. Default wingNames = {'wing1','wing2',
%   'wing3','wing4'}, which yields crop rectangles saved to wingLocs.wing1, 
%   wingLocs.wing2, etc. When method = crosshair, wings are processed 
%   clockwise from top left (i.e., top left, top right, bottom right, 
%   bottom left), and will be matched to wingNames in that order. When 
%   method = rectangles, wings are processed in the order specified by 
%   wingNames (the figure name specifies which wing to mark). wingLocs also 
%   includes a method field and cropRect (rectangle denoting the region 
%   containing all wings), and when method = crosshair, it also contains 
%   a center ([x y] of center click) field. Adds a square root 
%   transformation to images for visualization when nonlinVis is true 
%   (default). 
%
%   INPUT
%   im (matrix): image to process (required)
%   method (string): method to use to separate wings; options: 
%       'crosshair' (default): crop to wing region then separate using a click in the center (best when wings can be cleanly separated by a cross)
%       'rectangles': mark each wing using a separate rectangle (best when wings cannot be cleanly sparated)
%   wingNames (1 x 4 cell of strings): identifiers for each wing
%       for crosshair method, order = top left, top right, bottom right, bottom left
%       for rectangles method, order is based on user (each wing name is displayed in figure heading for user to mark)
%       default {'wing1','wing2','wing3','wing4'}
%   nonlinVis (boolean): generate nonlinear image for visualization? (default = true)
%
%   OUTPUT
%   wingLocs (structure): locations for each wing
%       contains a field for each wing (named based on wingNames) that contains a crop rectangle for the wing
%       crop rectangles are of the format [x y width height] (see doc imcrop)
%       wingLocs.method contains the method used to generate the locations
%       when method = crosshair, also contains cropRect and center fields, denoting the regions marked by the user (cropRect, center)
%
%   CREATES
%   n/a
%
%   RELIES ON
%   AddNonlin.m (if nonlinVis = true)
%   
%   Sandra Winters <sandra.winters@helsinki.fi>
%   updated 27 Jan 2025

%% check args & set defaults
if nargin<1
    error('image not provided')
end

if nargin<2 || isempty(method)
    method = 'crosshair';
end

if nargin<3 || isempty(wingNames)
    wingNames = {'wing1','wing2','wing3','wing4'};
end

if nargin<4
    nonlinVis = 1;
end

%TODO check args

%% mark wings
if nonlinVis
    im = AddNonlin(im);
end

%record method
wingLocs.method = method;

%display image
f = figure; ih = imshow(im);

%separate wings using specified method
if strcmpi(method,'crosshair')
    %crop image to wing region
    f.Name = 'crop to wing region, then double click inside crop';
    title('crop to wing region, then double click inside crop');
    % figure('Name','crop to wing region, then double click inside crop'); imshow(im)
    [~,wingLocs.cropRect] = imcrop(ih); 
    % [~,wingLocs.cropRect] = imcrop(im); 
    
    %mark center of wings
    title('click on the center point that separates the wings');
    wingLocs.center = ginput(1); close gcf

    %round to nearest pixel (for simpler calculations)
    wingLocs.cropRect = round(wingLocs.cropRect);
    wingLocs.center = round(wingLocs.center);

    %separate into wing rectangles -->
    %top left wing
    wingLocs.(wingNames{1}) = [wingLocs.cropRect(1) ... %x (col) = x1
                               wingLocs.cropRect(2) ... %y (row) = y1
                               wingLocs.center(1)-wingLocs.cropRect(1) ... %width = x2 - x1
                               wingLocs.center(2)-wingLocs.cropRect(2)]; %height = y2 - y1

    %top right wing
    wingLocs.(wingNames{2}) = [wingLocs.center(1) ... %x (col) = x2
                               wingLocs.cropRect(2) ... %y (row) = y1
                               wingLocs.cropRect(1) + wingLocs.cropRect(3) - wingLocs.center(1) ... %width = x1 + w - x2
                               wingLocs.center(2)-wingLocs.cropRect(2)]; %height = y2 - y1
    
    %bottom right wing
    wingLocs.(wingNames{3}) = [wingLocs.center(1) ... %x (col) = x2
                               wingLocs.center(2) ... %y (row) = y2
                               wingLocs.cropRect(1) + wingLocs.cropRect(3) - wingLocs.center(1) ... %width = x1 + w - x2
                               wingLocs.cropRect(2) + wingLocs.cropRect(4) - wingLocs.center(2)]; %height = y1 + h - y2

    %bottom left wing
    wingLocs.(wingNames{4}) = [wingLocs.cropRect(1) ... %x (col) = x1
                               wingLocs.center(2) ... %y (row) = y2
                               wingLocs.center(1) - wingLocs.cropRect(1) ... %width = x2 - x1
                               wingLocs.cropRect(2) + wingLocs.cropRect(4) - wingLocs.center(2)]; %height = y1 + h - y2
    
    % x1 = wingLocs.cropRect(1);
    % y1 = wingLocs.cropRect(2);
    % w = wingLocs.cropRect(3);
    % h = wingLocs.cropRect(4);
    % x2 = wingLocs.center(1);
    % y2 = wingLocs.center(2);

elseif strcmpi(method,'rectangles')
    %mark each wing as a rectangle
    for w = 1:4
        f.Name = ['crop to ' wingNames{w} ', then double click inside crop'];
        [~,wingLocs.(wingNames{w})] = imcrop(im);
    end
    close gcf
    
    %calculate crop for all wings
    minX = min([wingLocs.(wingNames{1})(1) ...
                wingLocs.(wingNames{2})(1) ...
                wingLocs.(wingNames{3})(1) ...
                wingLocs.(wingNames{4})(1)]);
    minY = min([wingLocs.(wingNames{1})(2) ...
                wingLocs.(wingNames{2})(2) ...
                wingLocs.(wingNames{3})(2) ...
                wingLocs.(wingNames{4})(2)]);
    maxX = max([wingLocs.(wingNames{1})(1) + wingLocs.(wingNames{1})(3) ...
                wingLocs.(wingNames{2})(1) + wingLocs.(wingNames{2})(3) ...
                wingLocs.(wingNames{3})(1) + wingLocs.(wingNames{3})(3) ...
                wingLocs.(wingNames{4})(1) + wingLocs.(wingNames{4})(3)]);
    maxY = max([wingLocs.(wingNames{1})(2) + wingLocs.(wingNames{1})(4) ...
                wingLocs.(wingNames{2})(2) + wingLocs.(wingNames{2})(4) ...
                wingLocs.(wingNames{3})(2) + wingLocs.(wingNames{3})(4) ...
                wingLocs.(wingNames{4})(2) + wingLocs.(wingNames{4})(4)]);
    wingLocs.cropRect = [minX minY maxX-minX maxY-minY];
else
    error("unknown method (options: 'crosshair','rectangles'")
end

end %function

